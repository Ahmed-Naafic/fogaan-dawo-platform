/**
 * ICE server configuration for consultation calls: STUN, plus Cloudflare TURN when configured.
 *
 * WEBRTC_STUN_URLS: comma-separated `stun:` / `stuns:` URLs. Unset → Google's public STUN server;
 * set to an empty value → no STUN (host candidates only — same-network calls only).
 *
 * Future TURN support plugs in here: add a provider that returns
 * { urls: ['turn:…', 'turns:…:443?transport=tcp'], username, credential } with SHORT-LIVED credentials
 * derived from a server-only shared secret (coturn "use-auth-secret"). The secret must never be
 * returned to clients; only the derived, expiring username/credential pair is.
 */
const DEFAULT_STUN = 'stun:stun.l.google.com:19302';
const STUN_URL = /^stuns?:[a-z0-9]([a-z0-9.-]{0,251}[a-z0-9])?(:\d{1,5})?$/i;

/** Parses WEBRTC_STUN_URLS. Returns { urls, invalid } (invalid entries are reported, never used). */
export function parseStunUrls(raw = process.env.WEBRTC_STUN_URLS) {
  const value = raw === undefined ? DEFAULT_STUN : raw;
  const entries = value
    .split(',')
    .map((s) => s.trim())
    .filter(Boolean);
  const urls = [];
  const invalid = [];
  for (const entry of entries) {
    const port = Number(entry.split(':')[2] ?? 3478);
    if (STUN_URL.test(entry) && port > 0 && port < 65536) urls.push(entry);
    else invalid.push(entry);
  }
  return { urls: [...new Set(urls)], invalid };
}

/** Providers of ICE servers. TURN can be added later as another entry without touching callers. */
const providers = [
  () => {
    const { urls } = parseStunUrls();
    return urls.length ? [{ urls }] : [];
  },
];

/** The RTCConfiguration.iceServers handed to an authorised participant (public data only). */
export function iceServersFor(/* { userId, consultationId } — for future per-user TURN credentials */) {
  return providers.flatMap((p) => p());
}

/**
 * TURN relay through Cloudflare Realtime (optional). When CLOUDFLARE_TURN_KEY_ID and
 * CLOUDFLARE_TURN_API_TOKEN are set, each participant gets SHORT-LIVED TURN credentials generated by
 * Cloudflare for this call (the API token never leaves the server). TURN carries the media when the two
 * devices cannot reach each other directly (mobile data, strict routers). Any failure falls back to STUN.
 */
const TURN_ENDPOINT = (keyId) => `https://rtc.live.cloudflare.com/v1/turn/keys/${encodeURIComponent(keyId)}/credentials/generate-ice-servers`;

export const turnConfigured = (env = process.env) => Boolean(env.CLOUDFLARE_TURN_KEY_ID && env.CLOUDFLARE_TURN_API_TOKEN);

/** Normalises Cloudflare's response ({ iceServers: [...] } or { iceServers: {...} }); drops port-53 URLs that browsers block. */
export function normaliseTurnResponse(body) {
  const list = Array.isArray(body?.iceServers) ? body.iceServers : body?.iceServers ? [body.iceServers] : [];
  return list
    .map((s) => ({ ...s, urls: (Array.isArray(s.urls) ? s.urls : [s.urls]).filter((u) => typeof u === 'string' && !/:53(\?|$)/.test(u)) }))
    .filter((s) => s.urls.length && s.urls.some((u) => /^turns?:/i.test(u)) && s.username && s.credential);
}

export async function turnServers({ fetchImpl = fetch, env = process.env } = {}) {
  if (!turnConfigured(env)) return [];
  const ttl = Math.min(Math.max(Number(env.TURN_CREDENTIAL_TTL_SECONDS) || 7200, 600), 86400);
  try {
    const res = await fetchImpl(TURN_ENDPOINT(env.CLOUDFLARE_TURN_KEY_ID), {
      method: 'POST',
      headers: { authorization: `Bearer ${env.CLOUDFLARE_TURN_API_TOKEN}`, 'content-type': 'application/json' },
      body: JSON.stringify({ ttl }),
      signal: AbortSignal.timeout(5000),
    });
    if (!res.ok) throw new Error(`TURN credentials request failed (${res.status})`);
    return normaliseTurnResponse(await res.json());
  } catch (error) {
    console.warn(`[webrtc] TURN unavailable, using STUN only: ${error.message}`);
    return [];
  }
}

/** ICE servers for a call: STUN plus, when configured, fresh TURN credentials. */
export async function iceServersForCall(who) {
  return [...iceServersFor(who), ...(await turnServers())];
}

/** Startup summary: a problem description or null. Names variables only. */
export function webrtcConfigProblem() {
  const { urls, invalid } = parseStunUrls();
  if (invalid.length) return `ignoring ${invalid.length} invalid WEBRTC_STUN_URLS entr${invalid.length === 1 ? 'y' : 'ies'}`;
  if (!urls.length) return 'no STUN server configured (WEBRTC_STUN_URLS is empty): calls work on the same network only';
  return null;
}
