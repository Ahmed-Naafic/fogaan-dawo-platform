const when = (iso, lang, timeZone = 'Africa/Mogadishu') =>
  `${new Date(iso).toLocaleString(lang === 'so' ? 'so-SO' : 'en-GB', { timeZone, day: '2-digit', month: 'short', year: 'numeric', hour: '2-digit', minute: '2-digit', hourCycle: 'h23' })} (${timeZone})`;

/** `lang`: 'en' (default) or 'so'. */
export function renderDemoReceipt(payment, { lang = 'en' } = {}) {
  const L = TEXT[lang] ?? TEXT.en;
  const language = TEXT[lang] ? lang : 'en';
  const success = payment.attempts.find((a) => a.status === 'SUCCEEDED');
  const refunded = payment.refunds.filter((r) => r.status === 'SUCCEEDED');
  const specialty = language === 'so' ? payment.appointment.doctor.specialty.nameSo : payment.appointment.doctor.specialty.nameEn;
  const lines = [
    { text: 'FOGAAN DAWO', size: 20, bold: true, gap: 0 },
    { text: L.title, size: 14, bold: true },
    { text: L.simulated, size: 10, bold: true },
    { rule: true, gap: 18 },
    { text: `${L.number}: ${payment.reference}`, bold: true },
    { text: `${L.paymentId}: ${payment.id}`, size: 9 },
    { text: `${L.paidOn}: ${when(payment.paidAt, language)}` },
    { text: `${L.method}: ${PROVIDER_NAMES[payment.provider] ?? payment.provider} (${L.simulatedShort})  -  ${L.wallet}: ${success?.wallet ?? '-'}` },
    { rule: true, gap: 18 },
    { text: `${L.patient}: ${payment.appointment.patient?.name ?? '-'}` },
    { text: `${L.doctor}: ${payment.appointment.doctor.name} - ${specialty}` },
    { text: `${L.consultation}: ${when(payment.appointment.startAtUtc, language)} (${L.video})` },
    { rule: true, gap: 18 },
    { text: `${L.amount}: ${payment.currency} ${payment.amount}`, size: 14, bold: true },
    ...refunded.map((r) => ({ text: `${L.refunded}: ${r.currency} ${r.amount} ${L.on} ${when(r.processedAt ?? r.createdAt, language)} (${L.simulatedShort})` })),
    { text: `${L.status}: ${L.statuses[payment.status] ?? payment.status}${refunded.length ? ` (${L.refundRecorded})` : ''}` },
    { rule: true, gap: 22 },
    { text: L.footer1, size: 9 },
    { text: L.footer2, size: 9 },
  ];
  return renderTextPdf(lines, { title: `${L.docTitle} ${payment.reference}` });
}

