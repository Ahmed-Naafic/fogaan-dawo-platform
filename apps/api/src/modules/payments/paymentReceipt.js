import { renderTextPdf } from '../../utils/simplePdf.js';

const PROVIDER_NAMES = { EVC_PLUS: 'EVC Plus', ZAAD: 'ZAAD', EDAHAB: 'eDahab' };
const when = (iso, timeZone = 'Africa/Mogadishu') =>
  `${new Date(iso).toLocaleString('en-GB', { timeZone, day: '2-digit', month: 'short', year: 'numeric', hour: '2-digit', minute: '2-digit', hourCycle: 'h23' })} (${timeZone})`;

/** DEMO receipt PDF for a presented, SUCCEEDED payment. Every page says it is simulated. */
export function renderDemoReceipt(payment) {
  const success = payment.attempts.find((a) => a.status === 'SUCCEEDED');
  const refunded = payment.refunds.filter((r) => r.status === 'SUCCEEDED');
  const lines = [
    { text: 'FOGAAN DAWO', size: 20, bold: true, gap: 0 },
    { text: 'DEMO PAYMENT RECEIPT', size: 14, bold: true },
    { text: 'SIMULATED TRANSACTION - NO REAL MONEY WAS TRANSFERRED', size: 10, bold: true },
    { rule: true, gap: 18 },
    { text: `Receipt number: ${payment.reference}`, bold: true },
    { text: `Payment ID: ${payment.id}`, size: 9 },
    { text: `Paid on: ${when(payment.paidAt)}` },
    { text: `Method: ${PROVIDER_NAMES[payment.provider] ?? payment.provider} (simulated)  -  Wallet: ${success?.wallet ?? '-'}` },
    { rule: true, gap: 18 },
    { text: `Patient: ${payment.appointment.patient?.name ?? '-'}` },
    { text: `Doctor: ${payment.appointment.doctor.name} - ${payment.appointment.doctor.specialty.nameEn}` },
    { text: `Consultation: ${when(payment.appointment.startAtUtc)} (video)` },
    { rule: true, gap: 18 },
    { text: `Amount paid: ${payment.currency} ${payment.amount}`, size: 14, bold: true },
    ...refunded.map((r) => ({ text: `Refunded: ${r.currency} ${r.amount} on ${when(r.processedAt ?? r.createdAt)} (simulated)` })),
    { text: `Status: ${payment.status}${refunded.length ? ' (refund recorded)' : ''}` },
    { rule: true, gap: 22 },
    { text: 'This is a demonstration receipt generated by the Fogaan Dawo test environment.', size: 9 },
    { text: 'It is not a tax invoice and is not proof of any real payment.', size: 9 },
  ];
  return renderTextPdf(lines, { title: `Fogaan Dawo demo receipt ${payment.reference}` });
}
